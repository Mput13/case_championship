def classify_tier(verdict: str) -> tuple[str, str]:
    v = (verdict or "").lower()
    if "кандидат на чартер" in v:
        return "charter", "Кандидат на чартер"
    if "кандидат на блок" in v:
        return "block", "Кандидат на блок мест"
    if "малый поток" in v:
        return "small", "Малый поток (<80 чел.)"
    if "проверить объём" in v:
        return "verify", "Поездки подтверждены"
    if "гипотеза" in v:
        return "hypothesis", "Гипотеза (связь)"
    if "есть закупки" in v:
        return "proc_only", "Закупки без маршрутов"
    return "none", "Нет подтверждённых поездок"


