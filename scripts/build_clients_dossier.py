def render_static_overview_rows(clients: list[dict]) -> str:
    rows = []
    for c in clients:
        ech_cls = f"e-{c['echelon']}"
        tier_cls = f"t-{c['tier']}"
        prod = c["offer"]["product"]
        if len(prod) > 125:
            prod = prod[:122] + "…"
        etp = c["etp"] or "—"
        if len(etp) > 42:
            etp = etp[:39] + "…"
        rows.append(
            f'<tr data-org="{html.escape(c["id"])}" tabindex="0">'
            f'<td class="num"><b>#{c["rank"]}</b></td>'
            f'<td><code>{html.escape(c["id"])}</code></td>'
            f'<td><b>{html.escape(c["name"])}</b><br><small class="muted">{html.escape(c["industry"] or c["category"])}</small></td>'
            f'<td><span class="badge {ech_cls}">{html.escape(c["echelonShort"])}</span><br>'
            f'<small class="muted">{html.escape(c["tierLabel"])}</small></td>'
            f'<td class="num">{c["pairsCount"]}</td>'
            f'<td class="num">{c["procCount"]}</td>'
            f'<td><small>{html.escape(etp)}</small></td>'
            f'<td><small>{html.escape(prod)}</small></td>'
            f'</tr>'
        )
    return "\n".join(rows)


