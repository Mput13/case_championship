def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model-dir", type=Path, default=DEFAULT_MODEL_DIR)
    parser.add_argument("--geojson", type=Path, default=DEFAULT_GEOJSON)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    dataset = build_dataset(args.model_dir, args.geojson)
    static_rows = render_static_overview_rows(dataset["clients"])
    data_json = json.dumps(dataset, ensure_ascii=False, separators=(",", ":"))
    # Guard against closing script tag inside JSON strings
    data_json = data_json.replace("</", "<\\/")

    out_html = (
        HTML_TEMPLATE
        .replace("__STATIC_ROWS__", static_rows)
        .replace("__DATA_JSON__", data_json)
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(out_html, encoding="utf-8")
    print(
        f"Generated {args.out} ({len(out_html)/1024:.1f} KB) | "
        f"clients={dataset['meta']['totalOrgs']} profiled={dataset['meta']['profiledOrgs']} "
        f"pairs={dataset['meta']['totalPairs']} sources={dataset['meta']['totalSourcesWithUrl']}"
    )


if __name__ == "__main__":
    main()
