# --- Albers Equal-Area Conic projection tailored for Russia ---
# Standard parallels 52N and 64N, central meridian 100E, origin 58N
_PHI1 = math.radians(52.0)
_PHI2 = math.radians(64.0)
_PHI0 = math.radians(58.0)
_LAM0 = math.radians(100.0)
_N = 0.5 * (math.sin(_PHI1) + math.sin(_PHI2))
_C = math.cos(_PHI1) ** 2 + 2.0 * _N * math.sin(_PHI1)
_RHO0 = math.sqrt(_C - 2.0 * _N * math.sin(_PHI0)) / _N


def albers_raw(lat: float, lon: float) -> tuple[float, float]:
    # Unwrap eastern Chukotka (negative west longitudes) past +180
    if lon < -100.0:
        lon += 360.0
    phi = math.radians(lat)
    lam = math.radians(lon)
    theta = _N * (lam - _LAM0)
    rho = math.sqrt(max(1e-9, _C - 2.0 * _N * math.sin(phi))) / _N
    x = rho * math.sin(theta)
    y = _RHO0 - rho * math.cos(theta)
    return x, y


def build_projector(geojson_path: Path, width: float = 960.0, height: float = 500.0, pad: float = 24.0):
    data = json.loads(geojson_path.read_text(encoding="utf-8"))
    geom = data["geometry"]
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]

    xs, ys = [], []
    for poly in polys:
        for ring in poly:
            for lon, lat in ring:
                x, y = albers_raw(lat, lon)
                xs.append(x)
                ys.append(y)

    min_x, max_x = min(xs), max(xs)
    min_y, max_y = min(ys), max(ys)
    span_x = max_x - min_x
    span_y = max_y - min_y
    scale = min((width - 2 * pad) / span_x, (height - 2 * pad) / span_y)
    ox = (width - span_x * scale) / 2.0
    oy = (height - span_y * scale) / 2.0

    def project(lat: float, lon: float) -> tuple[float, float]:
        x, y = albers_raw(lat, lon)
        sx = ox + (x - min_x) * scale
        sy = height - (oy + (y - min_y) * scale)
        return round(sx, 1), round(sy, 1)

    # Build SVG path for Russia land polygons (skipping tiny antimeridian crossing glitches)
    path_parts: list[str] = []
    for poly in polys:
        for ring in poly:
            if len(ring) < 3:
                continue
            pts = [project(lat, lon) for lon, lat in ring]
            # Split if a segment jumps wildly (antimeridian seam in source file)
            seg_cmd = [f"M{pts[0][0]},{pts[0][1]}"]
            for i in range(1, len(pts)):
                dx = abs(pts[i][0] - pts[i - 1][0])
                dy = abs(pts[i][1] - pts[i - 1][1])
                if dx > 120 or dy > 120:
                    seg_cmd.append(f"M{pts[i][0]},{pts[i][1]}")
                else:
                    seg_cmd.append(f"L{pts[i][0]},{pts[i][1]}")
            seg_cmd.append("Z")
            path_parts.append(" ".join(seg_cmd))

    # Subtle graticule lines (parallels 50, 60, 70; meridians 40, 60, 80, 100, 120, 140, 160)
    grat_parts: list[str] = []
    for lat in (50, 60, 70):
        pts = [project(lat, lon) for lon in range(20, 195, 5)]
        grat_parts.append("M" + " L".join(f"{x},{y}" for x, y in pts))
    for lon in (40, 60, 80, 100, 120, 140, 160):
        pts = [project(lat, lon) for lat in range(42, 78, 2)]
        grat_parts.append("M" + " L".join(f"{x},{y}" for x, y in pts))

    return project, " ".join(path_parts), " ".join(grat_parts)


def split_codes(text: str) -> list[str]:
    if not text:
        return []
    return [c.strip() for c in re.split(r"[;,\s]+", text) if c.strip()]


def parse_float(val: str) -> float | None:
    if not val:
        return None
    s = val.strip().replace(" ", "").replace("\u00a0", "").replace(",", ".")
    try:
        return float(s)
    except ValueError:
        return None


def parse_int(val: str) -> int | None:
    f = parse_float(val)
    return int(round(f)) if f is not None else None


