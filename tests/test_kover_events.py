"""Регрессия разбора постов Росавиации по аэропортам (src/kover_days.py, airport_events)."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from kover_days import airport_events

# пост 6495, 25.07.2026: личная пометка Самары не должна доставаться Нижнему Новгороду
p6495 = ("▫️Аэропорты\n\n— НИЖНИЙ НОВГОРОД (Чкалов)\n\n— САМАРА (Курумоч) ограничения сняты около 06:00 МСК\n\n"
         "— ЧЕБОКСАРЫ\n\n✈️ВВЕДЕНЫ временные ограничения на прием и выпуск воздушных судов.")
e = airport_events(p6495)
assert e["GOJ"] == "intro" and e["KUF"] == "lift" and e.get("CSY") == "intro", e
# два аэропорта с разным статусом
e = airport_events("Аэропорт ВНУКОВО — СНЯТЫ ограничения. Аэропорт НИЖНИЙ НОВГОРОД — ВВЕДЕНЫ ограничения на прием и выпуск")
assert e == {"VKO": "lift", "GOJ": "intro"}, e
# общий статус для списка в одной строке
e = airport_events("Аэропорты ВНУКОВО, ДОМОДЕДОВО — СНЯТЫ ограничения на прием и выпуск")
assert e == {"VKO": "lift", "DME": "lift"}, e
# сводка: статус перед списком
e = airport_events("Не принимают и не отправляют рейсы аэропорты: КАЗАНЬ, САМАРА")
assert e == {"KZN": "intro", "KUF": "intro"}, e
print("PASS: разбор статусов по аэропортам")
