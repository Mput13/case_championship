def d(a,b):
    (la1,lo1),(la2,lo2)=A[a],A[b]
    la1,lo1,la2,lo2=map(radians,(la1,lo1,la2,lo2))
    h=sin((la2-la1)/2)**2+cos(la1)*cos(la2)*sin((lo2-lo1)/2)**2
    return 2*6371*asin(sqrt(h))
