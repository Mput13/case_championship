def board(cid, tail):
    rows = [r for r in SCHEDULE if r['candidate_id'] == cid and r['state'] == 'REPLACE'
            and r['tail'] == tail and r['flight_id'] and r['departure_local']]
    lines = ['| День вылета | Плечи и местное время | Задания |', '|---|---|---|']
    for i in range(7):
        date = dt.date(2027, 2, 1) + dt.timedelta(days=i)
        rday = [r for r in rows if dt.datetime.fromisoformat(r['departure_local']).date() == date]
        rday.sort(key=lambda r: r['departure_utc'])
        legs = []
        for r in rday:
            dep, arr = map(dt.datetime.fromisoformat, [r['departure_local'], r['arrival_local']])
            arr_day = '' if arr.date() == dep.date() else f' ({arr:%d.%m})'
            legs.append(f"{r['origin']} {dep:%H:%M} → {r['destination']} {arr:%H:%M}{arr_day}")
        jobs = list(dict.fromkeys(r['old_or_new_id'] for r in rday))
        lines.append(f"| {days[i]} {date:%d.%m} | {'<br>'.join(legs) or 'Нет заданий в выбранной программе; другая работа UNKNOWN'} | {'; '.join(jobs) or '—'} |")
    carry = [r for r in rows if dt.datetime.fromisoformat(r['departure_local']).date() == dt.date(2027, 2, 8)]
    for r in carry:
        dep, arr = map(dt.datetime.fromisoformat, [r['departure_local'], r['arrival_local']])
        lines.append(f"| Переход: Пн 08.02 | {r['origin']} {dep:%H:%M} → {r['destination']} {arr:%H:%M} | {r['old_or_new_id']} |")
    return '\n'.join(lines)


