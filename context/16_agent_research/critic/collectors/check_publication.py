#!/usr/bin/env python3
"""Check this role's staged publication, without printing matched values."""
import ast
import csv
import datetime as dt
import hashlib
import json
from pathlib import Path
import re
import subprocess

BASE = Path(__file__).resolve().parents[1]
REPO = Path(subprocess.check_output(['git', 'rev-parse', '--show-toplevel'], text=True).strip())
PREFIX = BASE.relative_to(REPO).as_posix() + '/'
FORBIDDEN_KEYS = {'set-cookie', 'cookie', 'authorization', 'proxy-authorization'}
PATTERNS = {
    'private_key': re.compile(r'-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----'),
    'bearer_value': re.compile(r'(?i)\bBearer\s+[A-Za-z0-9_.~+/-]{20,}'),
    'github_token': re.compile(r'\b(?:gh[pousr]_[A-Za-z0-9]{24,}|github_pat_[A-Za-z0-9_]{35,})\b'),
    'jwt_value': re.compile(r'\beyJ[A-Za-z0-9_-]{12,}\.[A-Za-z0-9_-]{12,}\.[A-Za-z0-9_-]{12,}\b'),
    'email_contact': re.compile(r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b'),
    'labelled_phone': re.compile(r'(?i)(?:телефон|phone|tel)\s*[:=]\s*[+()\d][()\d .-]{9,}'),
}

def git(*args):
    return subprocess.check_output(['git', *args], cwd=REPO)

def forbidden_keys(obj, path):
    found = []
    if isinstance(obj, dict):
        for key, value in obj.items():
            if key.lower() in FORBIDDEN_KEYS:
                found.append({'path': path, 'kind': 'forbidden_http_header_key'})
            found.extend(forbidden_keys(value, path))
    elif isinstance(obj, list):
        for value in obj:
            found.extend(forbidden_keys(value, path))
    return found

def main():
    now = dt.datetime.now(dt.timezone.utc).isoformat()
    # Preserve an inventory of ignored research inputs, excluding generated bytecode.
    ignored = [x for x in git('ls-files', '--others', '--ignored', '--exclude-standard', '-z', '--', PREFIX).decode().split('\0') if x]
    inventory = []
    for name in sorted(ignored):
        path = REPO/name
        if '__pycache__' in path.parts or path.suffix == '.pyc' or not path.is_file():
            continue
        data = path.read_bytes()
        inventory.append({'path': path.relative_to(BASE).as_posix(), 'sha256': hashlib.sha256(data).hexdigest(),
                          'bytes': len(data), 'storage': 'LOCAL_IGNORED_PRESERVED'})
    (BASE/'local_raw_manifest.json').write_text(json.dumps({
        'generated_at_utc': now, 'path_base': PREFIX.rstrip('/'), 'file_count': len(inventory),
        'total_bytes': sum(x['bytes'] for x in inventory), 'policy': 'publication_policy.md', 'files': inventory,
    }, ensure_ascii=False, indent=2)+'\n')

    paths = [x for x in git('diff', '--cached', '--name-only', '--diff-filter=ACMR', '-z').decode().split('\0') if x]
    issues, sizes, syntax_count = [], [], 0
    for name in paths:
        if not name.startswith(PREFIX):
            issues.append({'path': name, 'kind': 'outside_role'}); continue
        rel = Path(name).relative_to(PREFIX.rstrip('/'))
        if 'raw' in rel.parts or rel.suffix in {'.pdf', '.html', '.png', '.zip', '.gz', '.pyc'}:
            issues.append({'path': name, 'kind': 'excluded_full_raw_or_binary'})
        data = git('show', ':'+name); sizes.append(len(data))
        if len(data) > 2_000_000:
            issues.append({'path': name, 'kind': 'large_staged_file'})
        text = data.decode('utf-8')
        for label, pattern in PATTERNS.items():
            if pattern.search(text):
                issues.append({'path': name, 'kind': label})
        if name.endswith('.json'):
            issues.extend(forbidden_keys(json.loads(text), name))
        elif name.endswith('.py'):
            ast.parse(text, filename=name); syntax_count += 1
        elif name.endswith('.csv'):
            list(csv.DictReader(text.splitlines()))
    result = {
        'checked_at_utc': now, 'scope': 'Staged critic paths only; no upstream repo audit',
        'staged_paths_checked': len(paths), 'all_within_role': all(x.startswith(PREFIX) for x in paths),
        'issues': issues, 'largest_staged_bytes': max(sizes, default=0), 'python_syntax_files': syntax_count,
        'raw_files_ignored_manifest': 'local_raw_manifest.json', 'ignored_file_count': len(inventory),
        'ignored_total_bytes': sum(x['bytes'] for x in inventory),
        'licence_handling': 'Full primary pages/PDF/extracts and copied raw exports excluded; facts/derived checks and metadata only',
        'acceptance_change': 'NONE; HOLD/UNKNOWN retained',
    }
    (BASE/'evidence/publication_check.json').write_text(json.dumps(result, ensure_ascii=False, indent=2)+'\n')
    print(json.dumps(result, ensure_ascii=False))
    if issues:
        raise SystemExit(1)

if __name__ == '__main__':
    main()
